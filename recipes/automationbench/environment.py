"""Harbor's environment interface implemented with the public CWSandbox SDK.

This environment supports the CPU-only, single-container tasks generated by run.py.
"""

import asyncio
import io
import json
import os
import re
import shlex
import tarfile
import uuid
from pathlib import Path, PurePosixPath

from cwsandbox import AuthStrategy, Sandbox, SandboxResourceExhaustedError
from harbor.environments.base import BaseEnvironment, ExecResult
from harbor.environments.capabilities import EnvironmentResourceCapabilities


def record_sandbox(path, sandbox_id):
    with Path(path).open("a") as stream:
        stream.write(json.dumps({"sandbox_id": sandbox_id}) + "\n")


class CoreWeaveEnvironment(BaseEnvironment):
    def __init__(
        self, *args, max_lifetime_seconds=3600, request_timeout_seconds=3100, **kwargs
    ):
        self.sandbox = None
        self.max_lifetime_seconds = max_lifetime_seconds
        self.request_timeout_seconds = request_timeout_seconds
        super().__init__(*args, **kwargs)

    @staticmethod
    def type():
        return "automationbench-cwsandbox"

    @classmethod
    def resource_capabilities(cls):
        return EnvironmentResourceCapabilities(
            cpu_request=True, cpu_limit=True, memory_request=True, memory_limit=True
        )

    def _validate_definition(self):
        # Required abstract method in Harbor's environment interface.
        if not self.task_env_config.docker_image:
            raise ValueError("This recipe requires a prebuilt CPU container image")
        if self.task_env_config.cpus != 2 or self.task_env_config.memory_mb != 4096:
            raise ValueError("This recipe requires 2 CPUs and 4096 MiB per task")
        if self.task_env_config.env:
            raise ValueError("Use the recipe's MODEL_* variables for the environment")

    async def start(self, force_build=False):
        self.sandbox = Sandbox(
            auth=AuthStrategy.COREWEAVE_API_KEY,
            container_image=self.task_env_config.docker_image,
            resources={
                "requests": {"cpu": "2", "memory": "4Gi"},
                "limits": {"cpu": "2", "memory": "4Gi"},
            },
            max_lifetime_seconds=self.max_lifetime_seconds,
            request_timeout_seconds=self.request_timeout_seconds,
            environment_variables={
                key: os.environ[key]
                for key in (
                    "MODEL_API_KEY",
                    "MODEL_NAME",
                    "MODEL_BASE_URL",
                    "MODEL_PROJECT",
                )
                if key in os.environ
            },
        )
        # Finish creation before cancellation cleanup so the ID is available.
        recorded = False
        creation = asyncio.ensure_future(self.sandbox.start())
        try:
            try:
                await asyncio.shield(creation)
            except asyncio.CancelledError:
                await creation
                raise
            if audit := os.environ.get("HARBOR_SANDBOX_AUDIT"):
                await asyncio.to_thread(record_sandbox, audit, self.sandbox.sandbox_id)
                recorded = True
            await asyncio.to_thread(
                self.sandbox.wait, timeout=self.task_env_config.build_timeout_sec
            )
            if str(self.sandbox.status) != "running":
                raise RuntimeError("Sandbox reached a terminal state during startup")
            result = await self.exec(
                "mkdir -p /logs/agent /logs/verifier /logs/artifacts /tests /solution",
                timeout_sec=30,
            )
            if result.return_code:
                raise RuntimeError("Could not initialize sandbox directories")
        except BaseException:
            try:
                await self.stop(delete=True)
            except Exception as exc:  # noqa: BLE001 -- retain the original startup failure
                self.logger.error("Startup cleanup failed (%s)", type(exc).__name__)
            raise
        finally:
            if (
                not recorded
                and self.sandbox.sandbox_id
                and (audit := os.environ.get("HARBOR_SANDBOX_AUDIT"))
            ):
                await asyncio.to_thread(record_sandbox, audit, self.sandbox.sandbox_id)

    async def stop(self, delete=True):
        if self.sandbox is not None and self.sandbox.sandbox_id:
            if delete:
                await Sandbox.delete(
                    self.sandbox.sandbox_id,
                    auth=AuthStrategy.COREWEAVE_API_KEY,
                    missing_ok=True,
                )
            else:
                await self.sandbox.stop(missing_ok=True)

    async def exec(self, command, cwd=None, env=None, timeout_sec=None, user=None):
        if self.sandbox is None:
            raise RuntimeError("Sandbox is not started")
        selected_user = user if user is not None else self.default_user
        if selected_user not in (None, "root", 0, "0"):
            raise ValueError(
                "This recipe runs its evaluator as the container's root user"
            )
        for key in env or {}:
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
                raise ValueError("Invalid environment variable name")
        if env:
            command = (
                "export "
                + " ".join(f"{key}={shlex.quote(value)}" for key, value in env.items())
                + "; "
                + command
            )
        result = await self.sandbox.exec(
            ["bash", "-lc", command], cwd=cwd, timeout_seconds=timeout_sec
        )
        return ExecResult(
            stdout=result.stdout, stderr=result.stderr, return_code=result.returncode
        )

    async def upload_file(self, source_path, target_path):
        result = await self.exec(
            "mkdir -p " + shlex.quote(str(PurePosixPath(target_path).parent)),
            timeout_sec=30,
        )
        if result.return_code:
            raise RuntimeError("Could not create upload directory")
        await self.sandbox.write_file(str(target_path), Path(source_path).read_bytes())

    async def download_file(self, source_path, target_path):
        data = await self.sandbox.read_file(str(source_path))
        target = Path(target_path)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)

    async def upload_dir(self, source_dir, target_dir):
        buffer = io.BytesIO()
        with tarfile.open(fileobj=buffer, mode="w:gz") as archive:
            archive.add(source_dir, arcname=".")
        remote = f"/tmp/automationbench-{uuid.uuid4().hex}.tar.gz"
        try:
            await self.sandbox.write_file(remote, buffer.getvalue())
            target = shlex.quote(str(target_dir))
            result = await self.exec(
                f"mkdir -p {target} && tar -xzf {remote} -C {target}", timeout_sec=120
            )
            if result.return_code:
                raise RuntimeError("Directory upload failed")
        finally:
            await self.exec(f"rm -f {remote}", timeout_sec=30)

    async def download_dir(self, source_dir, target_dir):
        if self.sandbox is None:
            return  # A pre-creation quota failure has no remote logs.
        remote = f"/tmp/automationbench-{uuid.uuid4().hex}.tar.gz"
        try:
            result = await self.exec(
                f"tar -czf {remote} -C {shlex.quote(str(source_dir))} .",
                timeout_sec=120,
            )
            if result.return_code:
                raise RuntimeError("Directory download failed")
            data = await self.sandbox.read_file(remote)
            Path(target_dir).mkdir(parents=True, exist_ok=True)
            with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
                archive.extractall(target_dir, filter="data")
        finally:
            await self.exec(f"rm -f {remote}", timeout_sec=30)


class QuotaOnceEnvironment(CoreWeaveEnvironment):
    """Controlled retry test: fail once before creating any sandbox."""

    injected = False

    async def start(self, force_build=False):
        if not type(self).injected:
            type(self).injected = True
            raise SandboxResourceExhaustedError(
                "Injected quota error for Harbor retry validation"
            )
        await super().start(force_build=force_build)
